/* Persistent dark / light theme control */
const themeToggle = document.getElementById("themeToggle");
const themeIcon = themeToggle.querySelector(".theme-icon");

function applyTheme(theme) {
  const isLight = theme === "light";
  document.documentElement.classList.toggle("light-theme", isLight);
  themeIcon.textContent = isLight ? "☾" : "☀";
  themeToggle.setAttribute("aria-label", isLight ? "Switch to dark mode" : "Switch to light mode");
  themeToggle.setAttribute("title", isLight ? "Dark mode" : "Light mode");
  try {
    localStorage.setItem("portfolio-theme", theme);
  } catch (error) {
    // Theme still works for the current page if storage is unavailable.
  }
}

const initialTheme = document.documentElement.classList.contains("light-theme") ? "light" : "dark";
applyTheme(initialTheme);

themeToggle.addEventListener("click", () => {
  const nextTheme = document.documentElement.classList.contains("light-theme") ? "dark" : "light";
  applyTheme(nextTheme);
});
